// ── WHAT YOU MEET AT SEA ─────────────────────────────────────────────────────────────────────────────────────
//
// An encounter used to be a modal: you checked your phone, a box said "you met a kraken and salvaged its
// hide", and you tapped Nice. The single most dramatic thing that can happen mid-voyage resolved itself while
// you were not looking, and the ship you had spent weeks building had nothing to do with the outcome.
//
// They are FIGHTS now, on the same engine as the fleet ladder, using the guns you actually own. Your voyage
// stops dead until you deal with it, and your phone is told — because a fight that resolves without you is
// the thing this replaces.
//
// TWO SHAPES, and the difference is what you can shoot at:
//
//   ship     Another hull. Canvas, timber and a gun deck, exactly like a fleet ship — you pick the part.
//   monster  A living thing. It has no rigging and no gun ports, so there is nothing to target but the animal
//            itself; every ball goes into it. It still hits BACK across your whole ship, because a kraken
//            does not care which part of you it is breaking.
//
// Difficulty runs 1–5. A tier-1 meeting is a nuisance you can lose a plank to; a tier-5 is a genuine wall you
// may want to run from. The reward is a named one-off — nothing that outruns the Forge, but nothing you can
// get anywhere else either, so a rare encounter is a story rather than a fragment.

