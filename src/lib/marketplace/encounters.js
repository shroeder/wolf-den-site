export const encounterArt = (id) => `/images/sailing/enc/${id}.png`;

/**
 * Which parts of this foe you are allowed to shoot at.
 *
 * A monster has no rigging and no gun ports — there is nothing on it to take off, so every ball goes into the
 * animal. This is the whole mechanical difference between the two shapes, and it is why a monster fight is a
 * race rather than a dismantling: you cannot blunt it first.
 */
// A ship offers canvas, timber and barrels. A creature offers its body and its LIMBS — which resolve through
// the same "guns" slot in the engine (severing one removes an attack, exactly as dismounting a cannon does),
// so nothing downstream needs a second code path. Only the words and the markers change.
export const encounterZones = (enc) => (enc?.kind === "monster" ? ["hull", "guns"] : ["sails", "hull", "guns"]);

/**
 * A voyage's encounter marks. Each is a fraction of the trip at which something may be waiting.
 *
 * It used to be exactly one, at the halfway point, on a Fortune-scaled roll. Three chances now — a third of
 * the way, halfway, and two thirds — each rolled independently, so a quiet voyage is still the common case
 * but a bad one can go wrong more than once. The later marks are rarer than the first on purpose: two fights
 * in a trip should feel like luck, and three like a story.
 */
export const ENCOUNTER_MARKS = [
    { at: 0.34, weight: 1 },      // the first roll, at the full rate
    { at: 0.5, weight: 0.55 },    // a second, a bit better than half as likely
    { at: 0.68, weight: 0.25 },   // and a third, uncommon
];

// ── WHAT IS ON THE TABLE ─────────────────────────────────────────────────────────────────────────────────────
// The same list the payout walks, turned into something the screen can draw. Both sides read `enc.loot`, so the
// spoils you are shown before you commit and the spoils you are handed after cannot drift apart — which is the
// only reason to show them at all. No words beyond a name and a count: the sprite says what it is.
const TITLE = (s) => s.charAt(0).toUpperCase() + s.slice(1);

export function lootPreview(loot = [], chestArt = {}, consumables = {}) {
    return loot.map((l) => {
        if (l.kind === "doubloons") return { kind: "doubloons", n: l.n, name: "Doubloons", art: "/images/sailing/doubloon.png" };
        // Pays doubloons now (see grantSeaSpoils in sailing.js) — the preview has to say what actually lands.
        if (l.kind === "fragment") return { kind: "doubloons", n: shardCoin(l.tier, l.n), name: "doubloons", art: "/images/sailing/doubloon.png" };
        // Chest sprites are generated blobs, not files on disk — the caller already holds the map.
        if (l.kind === "chest") return { kind: "chest", n: 1, tier: l.tier, name: `${TITLE(l.tier)} chest`, art: chestArt[l.tier] || null };
        if (l.kind === "parts") { const p = partForTier(l.tier); return { kind: "parts", n: l.n, name: p?.name || `Tier ${l.tier}`, art: p?.sprite || null, color: p?.color }; }
        // A consumable that resolved to nothing used to fall through to the chest-icon fallback, so a Pet
        // Treat was advertised as a wooden chest. Both its name and its sprite come from the caller's maps.
        if (l.kind === "consumable") {
            const c = consumables[l.id] || {};
            return { kind: "consumable", n: 1, id: l.id, name: c.name || null, art: c.art || null, emoji: c.emoji || null };
        }
        return { kind: l.kind, n: l.n || 1, name: null, art: null };
    });
}
