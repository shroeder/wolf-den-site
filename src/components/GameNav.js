// One icon, with the old emoji/react-icon kept as the fallback: a missing or not-yet-generated PNG degrades to
// exactly what shipped before rather than to a blank gap.
function NavIcon({ l, size, big = false }) {
    const [failed, setFailed] = useState(false);
    const k = NAV_SPRITE[l.href];
    const fallback = l.Icon
        ? <l.Icon className={big ? undefined : "game-nav-ico"} aria-hidden="true" />
        : l.sprite === "helmet" ? <SetsHelmet size={size} /> : <span aria-hidden="true">{l.emoji}</span>;
    if (!k || failed) return fallback;
    return (
        // eslint-disable-next-line @next/next/no-img-element
        <img
            className="game-nav-sprite" src={`/images/nav/${k}.png`} alt="" aria-hidden="true"
            width={size} height={size} style={{ width: size, height: size }} onError={() => setFailed(true)}
        />
    );
}
