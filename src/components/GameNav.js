// The Sets menu icon: the die-cut Warplate Helm sprite (falls back to a helmet emoji until it loads) — a real
// piece of gear reads far better here than the old puzzle-piece glyph.
function SetsHelmet({ size = 18 }) {
    const sprite = useItemSprite("warplate_helm");
    if (sprite) return <img src={sprite} alt="" width={size} height={size} style={{ width: size, height: size, objectFit: "contain", verticalAlign: "-0.28em" }} />;
    return <span aria-hidden="true">🪖</span>;
}
// Menu destination → its die-cut sprite in /public/images/nav (generated by scripts/gen-nav-icons.mjs).
// Keyed by href so the strip and the grid both pick it up without duplicating a field on 40-odd entries.
// Emoji belong to Apple and Google, render differently on every device, and looked borrowed sitting next to
// the game's own art. /marketplace/sets is deliberately missing — it uses the real Warplate Helm item sprite.
