const isOn = (pathname, href) => pathname === href || pathname.startsWith(`${href}/`);

// Paths that are part of the game shell but aren't their own nav destination — keep the menu visible on them.
const EXTRA_GAME_PATHS = ["/marketplace/u/", "/marketplace/fishing", "/marketplace/badges", "/marketplace/rewards", "/marketplace/farm", "/marketplace/trade", "/marketplace/friends", "/marketplace/inbox", "/marketplace/dm", "/marketplace/town", "/marketplace/auction", "/marketplace/cooking"];

export default function GameNav() {
    const pathname = usePathname() || "";
    const [menuOpen, setMenuOpen] = useState(false);
    const [signedIn, setSignedIn] = useState(false); // gates the Town link + the one-time Forge announcement — declared before `links`
    // The Kitchen is owner-gated. The nav asks the server rather than deciding locally, because "am I the owner"
    // isn't something the client knows and shouldn't be something it guesses.
    const [kitchen, setKitchen] = useState(false);
    useEffect(() => {
        let dead = false;
        fetch("/api/marketplace/cooking").then((r) => r.json()).then((d) => { if (!dead) setKitchen(Boolean(d?.unlocked)); }).catch(() => {});
        return () => { dead = true; };
    }, []);
    // (Fishing was owner-gated at launch prep; it's public now and rides `signedIn` like Town.)
    // Farm + Forge + Auction + Town are all live for every signed-in member now.
    const links = [...LINKS, { href: "/marketplace/farm", emoji: "🏡", label: "Farm" }, { href: "/marketplace/blacksmith", emoji: "🔨", label: "Forge" },
        { href: "/marketplace/auction", emoji: "🏛️", label: "Auction" },
        ...(signedIn ? [{ href: "/marketplace/town", emoji: "🏘️", label: "Town" }] : []),
        ...(signedIn ? [{ href: "/marketplace/fishing", emoji: "🎣", label: "Fishing" }] : []),
        ...(kitchen ? [{ href: "/marketplace/cooking", emoji: "🍳", label: "Kitchen" }] : [])];
    const inGame = links.some((l) => isOn(pathname, l.href)) || EXTRA_GAME_PATHS.some((p) => pathname === p || pathname.startsWith(p));

    const [chests, setChests] = useState(0);
    const [consumables, setConsumables] = useState(0); // unused potions/treats/relics — the Gear badge counts these too
    const [spins, setSpins] = useState(0);
    const [bossStrikes, setBossStrikes] = useState(0);
    const [questsReady, setQuestsReady] = useState(0);
    const [cropsReady, setCropsReady] = useState(0);
    const [petNudge, setPetNudge] = useState(0); // own pets you can still pet today (free daily reward)
    const [sailAttn, setSailAttn] = useState(false);
    const [castsLeft, setCastsLeft] = useState(0); // unthrown fishing casts — nudges people back to the rail
    const [featureClaims, setFeatureClaims] = useState({}); // claimable per-feature daily quests {farm,sailing,forge}
    useEffect(() => {
        if (!inGame) return undefined;
        let alive = true;
        const loadChests = () => {
            fetch("/api/marketplace/chests", { cache: "no-store" }).then((r) => (r.ok ? r.json() : null)).then((d) => { if (alive) setChests((d?.chests || []).reduce((s, c) => s + (c.count || 0), 0)); }).catch(() => {});
            fetch("/api/marketplace/spin", { cache: "no-store" }).then((r) => (r.ok ? r.json() : null)).then((d) => { if (!alive) return; setSignedIn(Boolean(d?.signedIn)); if (d?.signedIn) setSpins((d.freeAvailable ? 1 : 0) + (d.tokens || 0)); }).catch(() => {});
            fetch("/api/marketplace/boss/strikes", { cache: "no-store" }).then((r) => (r.ok ? r.json() : null)).then((d) => { if (alive) setBossStrikes(d?.attacksLeft || 0); }).catch(() => {});
            fetch("/api/marketplace/quests", { cache: "no-store" }).then((r) => (r.ok ? r.json() : null)).then((d) => { if (!alive) return; const qs = Array.isArray(d) ? d : (d?.quests || []); setQuestsReady(qs.filter((q) => q.done && !q.claimed).length); }).catch(() => {});
            fetch("/api/marketplace/sailing/status", { cache: "no-store" }).then((r) => (r.ok ? r.json() : null)).then((d) => { if (!alive) return; setSailAttn(Boolean(d?.attention)); }).catch(() => {});
            fetch("/api/marketplace/feature-daily?counts=1", { cache: "no-store" }).then((r) => (r.ok ? r.json() : null)).then((d) => { if (alive && d?.counts) setFeatureClaims(d.counts); }).catch(() => {});
            fetch("/api/marketplace/consumables", { cache: "no-store" }).then((r) => (r.ok ? r.json() : null)).then((d) => { if (alive) setConsumables((d?.stash || []).reduce((s2, c) => s2 + (c.count || 0), 0)); }).catch(() => {});
        };
        loadChests();
        const onRefresh = () => loadChests();
        window.addEventListener("wolfden-hud-refresh", onRefresh);
        return () => { alive = false; window.removeEventListener("wolfden-hud-refresh", onRefresh); };
    }, [inGame, pathname]);
    useEffect(() => {
        if (!inGame) return undefined;
        let alive = true;
        const load = () => fetch("/api/marketplace/farm", { cache: "no-store" }).then((r) => (r.ok ? r.json() : null)).then((d) => { if (!alive) return; setCropsReady(d?.garden?.readyCount || 0); setPetNudge(d?.petNudge || 0); }).catch(() => {});
        load();
        const onRefresh = () => load();
        window.addEventListener("wolfden-hud-refresh", onRefresh);
        return () => { alive = false; window.removeEventListener("wolfden-hud-refresh", onRefresh); };
    }, [inGame, pathname]);

    // Robustly pin the background while the full menu is open (overflow:hidden alone leaks scroll on mobile).
    useScrollLock(menuOpen);
    // Close on Escape.
    useEffect(() => {
        if (!menuOpen) return undefined;
        const onKey = (e) => { if (e.key === "Escape") setMenuOpen(false); };
        window.addEventListener("keydown", onKey);
        return () => window.removeEventListener("keydown", onKey);
    }, [menuOpen]);

    if (!inGame) return null;

    const plural = (n, w) => `${n} ${w}${n === 1 ? "" : "s"}`;
    const badgeInfo = (href) => {
        // Gear counts chests AND unused consumables: both are "you own something you haven't spent".
        if (href === "/marketplace/inventory" && (chests + consumables) > 0) {
            const bits = [];
            if (chests > 0) bits.push(plural(chests, "chest") + " to open");
            if (consumables > 0) bits.push(plural(consumables, "item") + " to use");
            return { badge: chests + consumables, title: bits.join(" · ") };
        }
        if (href === "/marketplace/boss" && bossStrikes > 0) return { badge: bossStrikes, title: `${plural(bossStrikes, "strike")} ready` };
        if (href === "/marketplace/spin" && spins > 0) return { badge: spins, title: `${plural(spins, "spin")} ready` };
        if (href === "/marketplace/quests" && questsReady > 0) return { badge: questsReady, title: `${plural(questsReady, "quest")} to claim` };
        // Feature pills also badge their claimable daily-quests (farm crops + quests together).
        if (href === "/marketplace/farm") { const n = cropsReady + petNudge + (featureClaims.farm || 0); if (n > 0) return { badge: n, title: [cropsReady ? `${plural(cropsReady, "crop")} ready` : null, petNudge ? `${plural(petNudge, "pet")} to pet` : null, featureClaims.farm ? `${plural(featureClaims.farm, "quest")} to claim` : null].filter(Boolean).join(" · ") }; }
        // Sailing badges claimable dailies OR unthrown casts — fishing happens during a voyage nobody watches,
        // so the ten free casts quietly expire unless something points at them. Casts win when both apply:
        // it's the one that's about to be lost.
        if (href === "/marketplace/sailing") {
            if (castsLeft > 0) return { badge: castsLeft, title: `${plural(castsLeft, "cast")} left — your line's out` };
            if ((featureClaims.sailing || 0) > 0) return { badge: featureClaims.sailing, title: `${plural(featureClaims.sailing, "quest")} to claim` };
        }
        if (href === "/marketplace/fishing" && castsLeft > 0) return { badge: castsLeft, title: `${plural(castsLeft, "cast")} left today` };
        if (href === "/marketplace/blacksmith" && (featureClaims.forge || 0) > 0) return { badge: featureClaims.forge, title: `${plural(featureClaims.forge, "quest")} to claim` };
        return { badge: null, title: null };
    };
    const dotFor = (href) => href === "/marketplace/sailing" && sailAttn;

    // The full, categorized grid menu — organized so you can see everything at once.
    const SECTIONS = [
        { title: "Play", items: [
            ...(signedIn ? [{ href: "/marketplace/town", emoji: "🏘️", label: "Town", sub: "Gather & raid" }] : []),
            { href: "/marketplace/boss", emoji: "⚔️", label: "Boss Fight", sub: "Join the raid" },
            { href: "/marketplace/sailing", emoji: "⛵", label: "Sailing", sub: "Voyage & dig" },
            { href: "/marketplace/farm", emoji: "🏡", label: "Farm", sub: "Grow & harvest" },
            { href: "/marketplace/spin", Icon: FaDharmachakra, label: "Daily Spin", sub: "Spin the wheel" },
            { href: "/marketplace/quests", emoji: "📜", label: "Quests", sub: "Daily bounties" },
            { href: "/marketplace/bounties", emoji: "🎯", label: "Bounties", sub: "Post & claim" },
            ...(signedIn ? [{ href: "/marketplace/fishing", emoji: "🎣", label: "Fishing", sub: "Log & records" }] : []),
            // The Kitchen is owner-gated. It has to be in the MENU as well as the scroll bar — the bar runs off
            // the side of the screen and a new entry appended to the end of it is, in practice, invisible.
            ...(kitchen ? [{ href: "/marketplace/cooking", emoji: "🍳", label: "The Kitchen", sub: "Cook what you farm" }] : []),
        ] },
        { title: "Gear & Pets", items: [
            { href: "/marketplace/inventory", emoji: "🛡️", label: "Your Gear", sub: "Equip items" },
            { href: "/marketplace/pets", emoji: "🐾", label: "Pets", sub: "Collect & equip" },
            { href: "/marketplace/sets", sprite: "helmet", label: "Sets", sub: "Set bonuses" },
            { href: "/marketplace/blacksmith", emoji: "🔨", label: "The Forge", sub: "Salvage & enhance" },
        ] },
        { title: "Shop & Trade", items: [
            { href: "/marketplace/store", emoji: "🛒", label: "Store", sub: "Buy supplies" },
            { href: "/marketplace/creations", emoji: "🎨", label: "Creations", sub: "Custom AI art" },
            { href: "/marketplace/trade", emoji: "🤝", label: "Trades", sub: "Swap gear & gold" },
            { href: "/marketplace/auction", emoji: "🏛️", label: "Auction House", sub: "List & buy gear" },
            { href: "/marketplace/credit", emoji: "💳", label: "Store Credit", sub: "Credit + coins" },
        ] },
        { title: "Progress & Social", items: [
            { href: "/marketplace/track", emoji: "🏆", label: "Rewards", sub: "Reward track" },
            { href: "/marketplace/badges", emoji: "🎖️", label: "Badges", sub: "Earn & show off" },
            { href: "/marketplace/leaderboard", emoji: "🥇", label: "Ranks", sub: "Leaderboard" },
            { href: "/marketplace/invite", emoji: "🎁", label: "Invite", sub: "500 gold each" },
            { href: "/marketplace/friends", emoji: "👥", label: "Friends", sub: "Add & message" },
            { href: "/marketplace/inbox", emoji: "✉️", label: "Inbox", sub: "Messages" },
        ] },
        { title: "You", items: [
            { href: "/marketplace/play", emoji: "🎮", label: "Game Home", sub: "The hub" },
            { href: "/marketplace/customize", emoji: "🧑‍🎨", label: "Customize", sub: "Avatar & card look" },
            { href: "/marketplace/profile", emoji: "👤", label: "Profile", sub: "Settings & account" },
        ] },
    ];

    return (
        <>
            {signedIn ? <ForgeAnnounce /> : null}
            {signedIn ? <FishingLaunch /> : null}
            <style>{GAMENAV_CSS}</style>
            <nav className="game-nav" aria-label="Game menu">
                <div className="game-nav-scroll">
                    <button type="button" className="game-nav-menu-btn" aria-label="Open full menu" aria-expanded={menuOpen} onClick={() => setMenuOpen(true)}>
                        <svg width="17" height="17" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><rect x="3" y="3" width="7.5" height="7.5" rx="1.6" /><rect x="13.5" y="3" width="7.5" height="7.5" rx="1.6" /><rect x="3" y="13.5" width="7.5" height="7.5" rx="1.6" /><rect x="13.5" y="13.5" width="7.5" height="7.5" rx="1.6" /></svg>
                        Menu
                    </button>
                    {links.map((l) => {
                        const { badge, title } = badgeInfo(l.href);
                        const dot = dotFor(l.href);
                        return (
                            <Link key={l.href} href={l.href} className={`game-nav-link${isOn(pathname, l.href) ? " is-active" : ""}${badge ? " has-badge" : ""}${dot ? " has-dot" : ""}`}>
                                {renderIcon(l)} {l.label}
                                {badge ? <span className="game-nav-badge" title={title}>{badge}</span> : null}
                                {dot ? <span className="game-nav-dot" title="Your boat has landed — time to dig!" aria-label="needs attention" /> : null}
                            </Link>
                        );
                    })}
                </div>
            </nav>

            {menuOpen ? (
                <div className="gm-overlay" onClick={() => setMenuOpen(false)} role="presentation">
                    <div className="gm-panel" onClick={(e) => e.stopPropagation()} role="dialog" aria-label="All game areas">
                        <div className="gm-head">
                            <strong>Where to?</strong>
                            <button type="button" className="gm-close" aria-label="Close menu" onClick={() => setMenuOpen(false)}>×</button>
                        </div>
                        <div className="gm-body">
                            {SECTIONS.map((sec) => (
                                <div key={sec.title} className="gm-section">
                                    <div className="gm-section-title">{sec.title}</div>
                                    <div className="gm-grid">
                                        {sec.items.map((it) => {
                                            const { badge, title } = badgeInfo(it.href);
                                            const dot = dotFor(it.href);
                                            return (
                                                <Link key={it.href} href={it.href} className={`gm-tile${isOn(pathname, it.href) ? " is-active" : ""}${it.owner ? " is-owner" : ""}`} onClick={() => setMenuOpen(false)}>
                                                    <span className="gm-tile-ico">{renderBigIcon(it)}</span>
                                                    <span className="gm-tile-label">{it.label}</span>
                                                    <span className="gm-tile-sub">{it.sub}</span>
                                                    {it.owner ? <span className="gm-tile-owner">owner</span> : null}
                                                    {badge ? <span className="gm-tile-badge" title={title}>{badge}</span> : null}
                                                    {dot ? <span className="gm-tile-dot" title="Needs attention" /> : null}
                                                </Link>
                                            );
                                        })}
                                    </div>
                                </div>
                            ))}
                        </div>
                    </div>
                </div>
            ) : null}
        </>
    );
}

