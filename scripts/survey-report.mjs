// Write docs/member-survey.md from the live rows. The survey is the only place members tell us what they want
// in their own words, and those words lived nowhere but Neon -- one TRUNCATE or one dropped round and 29
// wishes across three rounds are gone. This makes the doc reproducible instead of transcribed.
//
// Labels and the round constants are PARSED OUT OF survey.js rather than copied: survey.js is `server-only`
// and imports the db, so a plain node script cannot import it, but a second hand-maintained copy of the
// system list is a list that silently stops matching the one members are shown.
//
//   node scripts/survey-report.mjs            rewrites docs/member-survey.md
//
// Re-run it when a round closes; the "as of" line and the open/closed banner move on their own.
import fs from "node:fs";
import { neon } from "@neondatabase/serverless";

const env = fs.readFileSync("C:/Users/Luke/Projects/accounting_app/.env", "utf8");
const sql = neon(env.match(/^DATABASE_URL=["']?([^"'\r\n]+)/m)[1]);

const src = fs.readFileSync("src/lib/marketplace/survey.js", "utf8");
const pick = (re) => [...src.matchAll(re)].map((m) => [m[1], m[2]]);
const LABELS = Object.fromEntries(pick(/\{\s*key:\s*"([^"]+)",\s*label:\s*"([^"]+)"/g));
const ROUND = Number(src.match(/SURVEY_ROUND\s*=\s*(\d+)/)[1]);
const OPENS = src.match(/SURVEY_OPENS\s*=\s*Date\.parse\("([^"]+)"\)/)[1];
const CLOSES = src.match(/SURVEY_CLOSES\s*=\s*Date\.parse\("([^"]+)"\)/)[1];
const MIN_ACTIONS = Number(src.match(/SURVEY_MIN_ACTIONS\s*=\s*(\d+)/)[1]);
const name = (k) => (k ? LABELS[k] || k : "—");

const day = (d) => new Date(d).toISOString().slice(0, 10);
const stamp = (d) => new Date(d).toISOString().slice(0, 16).replace("T", " ") + " UTC";

const rounds = await sql`SELECT round, COUNT(*)::int n, MIN(created_at) first, MAX(updated_at) last
                           FROM mkt_survey_response GROUP BY round ORDER BY round`;

// One tally query shape, run per round per column. `least` and `more` were asked in different rounds, so a
// column with no rows is a question that round did not ask -- rendered as absent, never as a row of zeros.
const tally = async (round, col) => {
    const rows = await sql.query(
        `SELECT ${col} k, COUNT(*)::int n FROM mkt_survey_response
          WHERE round = $1 AND ${col} IS NOT NULL GROUP BY 1 ORDER BY 2 DESC, 1`, [round]);
    return rows;
};
const table = (rows, head) => rows.length
    ? [`| ${head} | n |`, "|---|---|", ...rows.map((r) => `| ${name(r.k)} | ${r.n} |`), ""].join("\n")
    : "";

const out = [];
out.push("# The member survey", "");
out.push("<!-- GENERATED by scripts/survey-report.mjs -- re-run it, do not hand-edit. -->", "", "");
out.push(`Every round, in full: the tallies and **every** word of free text. Generated ${stamp(Date.now())}.`, "");
out.push("The questions are deliberately unchanged between rounds so the numbers stay comparable; the system",
    "list grows as the Den does. Keys are stable. See `src/lib/marketplace/survey.js` for the live round,",
    "the window, and who gets asked.", "");

const now = Date.now();
const open = now >= Date.parse(OPENS) && now < Date.parse(CLOSES);
out.push(`**Round ${ROUND}** is the live round: opened ${stamp(OPENS)}, closes ${stamp(CLOSES)}, shown to members`,
    `with at least ${MIN_ACTIONS.toLocaleString()} account actions in the last 30 days. Answering pays one mythic`,
    "chest, once per member ever.", "");
out.push(open
    ? `> ⚠️ Round ${ROUND} was **still open** when this was generated. Re-run the script after ${stamp(CLOSES)} for the final tally.`
    : `Round ${ROUND} is closed. These numbers are final.`, "");

for (const r of [...rounds].reverse()) {
    const [fav, lst, mor, pce, all] = await Promise.all([
        tally(r.round, "favorite"), tally(r.round, "least"), tally(r.round, "more"), tally(r.round, "pace"),
        sql`SELECT COALESCE(b.display_name, b.alias, split_part(b.email, '@', 1)) name,
                   s.favorite, s.least, s.more, s.pace, s.wish, s.updated_at
              FROM mkt_survey_response s JOIN mkt_buyer b ON b.id = s.buyer_id
             WHERE s.round = ${r.round} ORDER BY s.updated_at DESC`,
    ]);
    out.push("---", "", `## Round ${r.round} — ${r.n} responses`, "");
    out.push(day(r.first) === day(r.last) ? `${day(r.first)}.` : `${day(r.first)} to ${day(r.last)}.`, "");
    out.push(table(fav, "Favourite"));
    out.push(table(mor, "Would want more of"));
    out.push(table(lst, "Least favourite"));
    if (pce.length) {
        out.push("**Pace — would you play something hands-on?**", "");
        out.push(table(pce, "Answer"));
    }
    const notes = all.filter((x) => x.wish && x.wish.trim());
    out.push(`### Free text (${notes.length} of ${r.n})`, "");
    if (!notes.length) out.push("_None._", "");
    for (const x of notes) {
        out.push(`**${x.name || "Member"}** · ${day(x.updated_at)} · favourite: ${name(x.favorite)}`);
        out.push("", `> ${x.wish.replace(/\r?\n/g, "\n> ")}`, "");
    }
    out.push("<details><summary>Every response, newest first</summary>", "");
    out.push("| Member | Favourite | Wants more | Least | Pace | When |", "|---|---|---|---|---|---|");
    for (const x of all) {
        out.push(`| ${x.name || "Member"} | ${name(x.favorite)} | ${name(x.more)} | ${name(x.least)} | ${name(x.pace)} | ${day(x.updated_at)} |`);
    }
    out.push("", "</details>", "");
}

fs.mkdirSync("docs", { recursive: true });
// Joined verbatim -- blank lines are placed deliberately above, because a markdown table dies without them.
const NL = String.fromCharCode(10);
fs.writeFileSync("docs/member-survey.md", out.join(NL).replace(new RegExp(NL + "{3,}", "g"), NL + NL).trimEnd() + NL);
console.log(`docs/member-survey.md written -- ${rounds.map((r) => `r${r.round}:${r.n}`).join(" ")}`);
